#!/usr/bin/env python3
"""Export the frozen M3 counts+Twin expert as a small C decision tree."""
from __future__ import annotations

import hashlib
from pathlib import Path

from host.train.m2_event_replay_20261020 import ROOT, train_experts

OUT = ROOT / "main" / "m3_model.h"


def render() -> str:
    features, clf = train_experts()[0]
    tree = clf.tree_
    used = [name for index, name in enumerate(features) if index in set(tree.feature) - {-2}]

    def branch(node: int, indent: str) -> list[str]:
        if tree.children_left[node] == tree.children_right[node]:
            choice = int(tree.value[node][0].argmax())
            return [f"{indent}return {choice};"]
        name = features[tree.feature[node]]
        threshold = repr(float(tree.threshold[node]))
        return ([f"{indent}if (f->{name} <= {threshold}) {{"]
                + branch(int(tree.children_left[node]), indent + "    ")
                + [f"{indent}}} else {{"]
                + branch(int(tree.children_right[node]), indent + "    ")
                + [f"{indent}}}"])

    source = Path(__file__).read_bytes()
    lines = [
        "/* Generated by host/train/export_m3_model_20261021.py; do not edit. */",
        f"/* Exporter SHA256: {hashlib.sha256(source).hexdigest()} */",
        f"/* Training: frozen train_experts()[0]; {tree.node_count} nodes, depth {tree.max_depth}. */",
        "#ifndef NIDS_M3_MODEL_H", "#define NIDS_M3_MODEL_H", "",
        "typedef struct {",
    ]
    lines += [f"    float {name};" for name in used]
    lines += ["} nids_m3_features_t;", "", "static inline int nids_m3_predict(const nids_m3_features_t *f)", "{"]
    lines += branch(0, "    ")
    lines += ["}", "", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="ascii")
    print(OUT)
